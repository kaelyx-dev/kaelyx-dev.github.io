import {
  defineNuxtModule, addTemplate, addTypeTemplate, addServerTemplate, addNitroPlugin,
  addImports, addComponent, createResolver, getLayerDirectories, updateTemplates, useLogger,
} from '@nuxt/kit'
import { readFile, readdir } from 'node:fs/promises'
import { relative, resolve } from 'pathe'
import { withDefaults } from '@kaelyx/ts-kit/object'
import { toIconName } from './lib/normalise'
import { svgToSymbol, toSprite } from './lib/symbol'

export interface IconsOptions {
  dir?: string             // relative to each layer's srcDir, so app/assets/icons by default
  prefix?: string          // symbol id prefix, keeps icon ids from clashing with ids on the page
  splitCamelCase?: boolean // ArrowLeft -> arrow-left, but also GitHub -> git-hub
  acronyms?: string[]      // passed to convertCase, e.g. ['GQL'] keeps GQLLogo as gql-logo
  currentColor?: boolean   // rewrite fill/stroke colours to currentColor (breaks multi-colour icons)
}

declare module '@nuxt/schema' {
  interface NuxtConfig { icons?: IconsOptions }
}

const DEFAULTS = {
  dir: 'assets/icons',
  prefix: 'icon-',
  splitCamelCase: true,
  acronyms: [] as string[],
  currentColor: false,
} satisfies Required<IconsOptions>

interface Icon {
  file: string
  viewBox: string
  markup: string
}

export default defineNuxtModule<IconsOptions>({
  meta: { name: 'icons', configKey: 'icons' },
  defaults: DEFAULTS,
  async setup(options, nuxt) {
    const { resolve: r } = createResolver(import.meta.url)
    const logger = useLogger('icons')
    const opts = withDefaults(options, DEFAULTS)
    const rel = (path: string) => relative(nuxt.options.rootDir, path)

    const loadLayer = async (dir: string, icons: Map<string, Icon>) => {
      const entries = await readdir(dir, { recursive: true }).catch(() => [])
      const files = entries.filter(file => file.toLowerCase().endsWith('.svg')).sort()
      const named = new Map<string, string>()

      for (const file of files) {
        const path = resolve(dir, file)
        const name = toIconName(relative(dir, path), opts)
        if (!name.ok) {
          logger.warn(`Skipping ${rel(path)}: ${name.error}`)
          continue
        }

        // two files in the same layer can't be told apart once normalised, so make the author pick
        const clash = named.get(name.value)
        if (clash) throw new Error(`[icons] ${rel(clash)} and ${rel(path)} both normalise to "${name.value}"`)
        named.set(name.value, path)

        if (/[^a-z0-9-]/.test(name.value)) logger.warn(`Icon "${name.value}" (${rel(path)}) has non-ASCII characters in its name`)

        const symbol = svgToSymbol(`${opts.prefix}${name.value}`, await readFile(path, 'utf8'), opts)
        if (!symbol.ok) {
          logger.warn(`Skipping ${rel(path)}: ${symbol.error}`)
          continue
        }

        const replaced = icons.get(name.value)
        if (replaced) logger.info(`"${name.value}" from ${rel(path)} replaces ${rel(replaced.file)}`)
        icons.set(name.value, { file: path, ...symbol.value })
      }

      if (named.size) logger.info(`${named.size} icon(s) from ${rel(dir)}: ${[...named.keys()].join(', ')}`)
    }

    // _layers[0] is the root project, so walk from the deepest layer up and let the root win
    const layerDirs = getLayerDirectories(nuxt)
    const dirs = [...nuxt.options._layers.entries()].reverse().map(([index, layer]) => {
      // only dir is per layer; the other options apply to every icon, so they come from the merged config
      const { dir } = withDefaults(layer.config.icons as IconsOptions | undefined, { dir: DEFAULTS.dir })
      return resolve(layerDirs[index]!.app, dir)
    })

    // Swapped in whole by scan(), which the templates below read from when (re)generated
    let names: string[] = []
    let icons = new Map<string, Icon>()
    let sprite = ''

    const scan = async () => {
      const next = new Map<string, Icon>()
      for (const dir of dirs) await loadLayer(dir, next)

      icons = next
      names = [...icons.keys()].sort()
      sprite = names.length ? toSprite(names.map(name => icons.get(name)!.markup)) : ''

      if (icons.size) logger.success(`Sprite built: ${icons.size} icon(s), ${(Buffer.byteLength(sprite) / 1024).toFixed(1)} kB`)
      else logger.warn(`No icons found in:\n${dirs.map(dir => `  ${rel(dir)}`).join('\n')}`)
    }
    await scan()

    // A real .ts module so the data and the IconName type come from one place
    const data = addTemplate({
      filename: 'icons.ts',
      write: true,
      getContents: () => {
        const meta = Object.fromEntries(names.map(name => [name, {
          id: `${opts.prefix}${name}`,
          viewBox: icons.get(name)!.viewBox,
        }]))

        return [
          '// Generated by modules/001.module.icons',
          'export interface IconMeta { id: string; viewBox: string }',
          `export type IconName = ${names.map(name => JSON.stringify(name)).join(' | ') || 'never'}`,
          `export const icons: Readonly<Record<IconName, IconMeta>> = ${JSON.stringify(meta, null, 2)}`,
          'export const iconNames = Object.keys(icons) as IconName[]',
          '',
        ].join('\n')
      },
    })
    nuxt.options.alias['#icons'] = data.dst

    // The sprite only exists server-side, so it never ends up in the client bundle. A build inlines it;
    // dev reads it from a file on every render, as the Nitro bundle isn't rebuilt when icons change
    const spriteFile = addTemplate({ filename: 'icons-sprite.svg', write: true, getContents: () => sprite })
    addServerTemplate({
      filename: '#icons-sprite',
      getContents: () => nuxt.options.dev
        ? `import { readFile } from 'node:fs/promises'\nexport default () => readFile(${JSON.stringify(spriteFile.dst)}, 'utf8')`
        : `export default () => ${JSON.stringify(sprite)}`,
    })
    addTypeTemplate({
      filename: 'types/icons-sprite.d.ts',
      getContents: () => `declare module '#icons-sprite' { const getSprite: () => string | Promise<string>; export default getSprite }`,
    }, { nitro: true, nuxt: false })

    addNitroPlugin(r('./runtime/server/sprite'))

    if (nuxt.options.dev) {
      // icon dirs inside a layer's app/ are already watched; this adds any configured outside it
      nuxt.options.watch.push(...dirs)

      // Regenerating icons.ts makes Vite reload the page, as nothing that imports it accepts hot updates.
      // Queued so a burst of changes (deleting a folder) rescans in order rather than all at once
      let queue = Promise.resolve()
      nuxt.hook('builder:watch', (event, relativePath) => {
        const path = resolve(nuxt.options.srcDir, relativePath)
        const inIconDir = dirs.some(dir => path.startsWith(`${dir}/`))
        if (!inIconDir || !(path.toLowerCase().endsWith('.svg') || event === 'unlinkDir')) return

        logger.info(`${event} ${rel(path)}, rebuilding icons`)
        queue = queue
          .then(scan)
          .then(() => updateTemplates({ filter: t => t.filename === 'icons.ts' || t.filename === 'icons-sprite.svg' }))
          .catch(error => logger.error(error))
      })
      logger.info(`Watching ${dirs.length} folder(s) for icon changes`)
    }

    addImports([
      { name: 'useIcon', from: r('./runtime/useIcon') },
      { name: 'isIconName', from: r('./runtime/useIcon') },
      { name: 'IconName', from: '#icons', type: true },
    ])
    addComponent({ name: 'Icon', filePath: r('./runtime/Icon.vue') })
  },
})
