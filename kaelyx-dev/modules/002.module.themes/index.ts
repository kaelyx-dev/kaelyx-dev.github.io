import {
  defineNuxtModule, addTemplate, addTypeTemplate, addServerTemplate, addNitroPlugin, addPlugin,
  addImports, createResolver, getLayerDirectories, useLogger,
} from '@nuxt/kit'
import { readFile, readdir } from 'node:fs/promises'
import { basename, dirname, relative, resolve } from 'pathe'
import { parseConf } from '../000.module.kv/runtime/parse'
import { checkThemeName, toLabel, toScheme, toThemeConfig, type ThemeConfig, type ThemeScheme } from './lib/config'
import { readThemeFile } from './lib/theme-file'
import { toColorSchemeMeta, toHeadScript } from './lib/head'

const THEME_DIR = 'assets/themes'
const ATTRIBUTE = 'data-theme'

interface Theme {
  file: string
  scheme?: ThemeScheme
}

export default defineNuxtModule({
  meta: { name: 'themes' },
  async setup(_options, nuxt) {
    const { resolve: r } = createResolver(import.meta.url)
    const logger = useLogger('themes')
    const rel = (path: string) => relative(nuxt.options.rootDir, path)

    const confFile = r('./config/themes.conf')
    const defaults = parseConf(await readFile(confFile, 'utf8'))
    nuxt.options.watch.push(confFile)

    const dirs = [...getLayerDirectories(nuxt)].reverse().map(layer => resolve(layer.app, THEME_DIR))
    const themes = new Map<string, Theme>()

    for (const dir of dirs) {
      const entries = await readdir(dir, { withFileTypes: true }).catch(() => [])
      const files = entries
        .filter(entry => entry.isFile() && entry.name.endsWith('.scss') && !entry.name.startsWith('_'))
        .map(entry => entry.name)
        .sort()

      for (const file of files) {
        const path = resolve(dir, file)
        const name = checkThemeName(basename(file, '.scss'))
        if (!name.ok) throw new Error(`[themes] ${rel(path)}: ${name.error}`)

        const meta = readThemeFile(await readFile(path, 'utf8'))
        if (!meta.ok) throw new Error(`[themes] ${rel(path)} ${meta.error}`)

        const replaced = themes.get(name.value)
        if (replaced) logger.info(`"${name.value}" from ${rel(path)} replaces ${rel(replaced.file)}`)
        themes.set(name.value, { file: path, scheme: meta.value.scheme })
      }
    }

    const names = [...themes.keys()].sort()
    if (!names.length) throw new Error(`[themes] No themes found. Add one, e.g. ${rel(resolve(dirs.at(-1)!, 'light.scss'))}`)

    let config: ThemeConfig | undefined
    const getConfig = () => {
      if (!config) throw new Error('[themes] Read the config before kv:extend ran; modules/000.module.kv is required')
      return config
    }

    nuxt.hook('kv:extend', (kv) => {
      for (const [key, value] of Object.entries(defaults)) if (!(key in kv)) kv[key] = value

      const result = toThemeConfig(kv, names)
      if (!result.ok) throw new Error(`[themes] ${result.error}`)
      config = result.value

      const { system } = config
      logger.info(`${names.length} theme(s): ${names.join(', ')}. Default ${config.default}, `
        + (system.follow ? `system light -> ${system.light}, dark -> ${system.dark}` : 'not following the OS'))
    })

    const schemeOf = (name: string) => toScheme(name, themes.get(name)!.scheme, getConfig())
    const labelOf = (name: string) => getConfig().labels[name] ?? toLabel(name)
    const from = (dst: string, path: string) => relative(dirname(dst), path)

    const api = addTemplate({
      filename: 'themes/_api.scss',
      write: true,
      getContents: (): string => [
        '// Generated by modules/002.module.themes. Use it as: @use \'@themes/api\' as theme;',
        `@forward '${from(api.dst, r('./scss/api'))}' with (`,
        `  $roles: (${getConfig().roles.join(', ')},),`,
        `  $attribute: '${ATTRIBUTE}',`,
        ');',
        '',
      ].join('\n'),
    })
    nuxt.options.alias['@themes'] = dirname(api.dst)

    const sheet = addTemplate({
      filename: 'themes/_themes.scss',
      write: true,
      getContents: (): string => {
        const { default: fallback, roles } = getConfig()
        const ordered = [fallback, ...names.filter(name => name !== fallback)]

        return [
          '// Generated by modules/002.module.themes',
          '@use \'@themes/api\' as theme;',
          ...ordered.map((name, i) => `@use '${from(sheet.dst, themes.get(name)!.file)}' as t${i};`),
          '',
          '// A cascade layer, so any unlayered app or component style wins whatever its specificity or order',
          '@layer themes {',
          ...ordered.map((name, i) =>
            `  @include theme.define(${name}, t${i}.$tokens, $default: ${name === fallback}, $scheme: ${schemeOf(name)});`),
          '',
          `  :root { @include theme.use-tone(${roles[0]}); }`,
          '  @include theme.tone-selectors;',
          '}',
          '',
        ].join('\n')
      },
    })

    const entry = addTemplate({
      filename: 'themes/entry.scss',
      write: true,
      getContents: () => '// Generated by modules/002.module.themes\n@use \'@themes/themes\';\n',
    })

    nuxt.options.css.unshift(entry.dst)

    const data = addTemplate({
      filename: 'themes.ts',
      write: true,
      getContents: () => {
        const { default: fallback, storageKey, roles, system } = getConfig()
        const union = (list: string[]) => list.map(item => JSON.stringify(item)).join(' | ') || 'never'
        const meta = Object.fromEntries(names.map(name => [name, { name, label: labelOf(name), scheme: schemeOf(name) }]))

        return [
          '// Generated by modules/002.module.themes',
          'export type ThemeScheme = \'light\' | \'dark\'',
          `export type ThemeName = ${union(names)}`,
          `export type ThemeRole = ${union(roles)}`,
          'export interface ThemeMeta { name: ThemeName; label: string; scheme: ThemeScheme }',
          `export const themes: Readonly<Record<ThemeName, ThemeMeta>> = ${JSON.stringify(meta, null, 2)}`,
          'export const themeNames = Object.keys(themes) as ThemeName[]',
          `export const themeRoles = ${JSON.stringify(roles)} as const satisfies readonly ThemeRole[]`,
          'export const themeConfig = {',
          `  attribute: ${JSON.stringify(ATTRIBUTE)},`,
          `  storageKey: ${JSON.stringify(storageKey)},`,
          `  default: ${JSON.stringify(fallback)} as ThemeName,`,
          `  system: { follow: ${system.follow}, light: ${JSON.stringify(system.light)} as ThemeName, dark: ${JSON.stringify(system.dark)} as ThemeName },`,
          '} as const',
          '',
        ].join('\n')
      },
    })
    nuxt.options.alias['#themes'] = data.dst

    addServerTemplate({
      filename: '#themes-head',
      getContents: () => {
        const { default: fallback, storageKey, system } = getConfig()
        const script = toHeadScript({ names, attribute: ATTRIBUTE, storageKey, fallback, system })
        const scheme = toColorSchemeMeta(names.map(schemeOf))
        return `export default ${JSON.stringify(`<meta name="color-scheme" content="${scheme}"><script>${script}</script>`)}`
      },
    })
    addTypeTemplate({
      filename: 'types/themes-head.d.ts',
      getContents: () => `declare module '#themes-head' { const head: string; export default head }`,
    }, { nitro: true, nuxt: false })

    addNitroPlugin(r('./runtime/server/head'))
    addPlugin({ src: r('./runtime/plugin.client'), mode: 'client' })

    if (nuxt.options.dev) {
      nuxt.hook('builder:watch', async (event, relativePath) => {
        if (event !== 'add' && event !== 'unlink') return
        const path = resolve(nuxt.options.srcDir, relativePath)
        if (!path.endsWith('.scss') || !dirs.some(dir => path.startsWith(`${dir}/`))) return

        logger.info(`${event} ${rel(path)}, restarting to update the theme list`)
        await nuxt.callHook('restart')
      })
    }

    addImports([
      { name: 'useTheme', from: r('./runtime/useTheme') },
      { name: 'isThemeName', from: r('./runtime/useTheme') },
      { name: 'isThemePreference', from: r('./runtime/useTheme') },
      { name: 'ThemePreference', from: r('./runtime/useTheme'), type: true },
      { name: 'themeRoles', from: '#themes' },
      ...['ThemeName', 'ThemeMeta', 'ThemeRole', 'ThemeScheme'].map(name => ({ name, from: '#themes', type: true })),
    ])
  },
})
